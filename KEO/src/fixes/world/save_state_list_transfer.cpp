 if(!island)return false;
 const __int64 delta=(__int64)(uintptr_t)island-(__int64)(uintptr_t)(site+6);
 if(delta<-2147483647LL-1||delta>2147483647LL){VirtualFree(island,0,MEM_RELEASE);return false;}
