bool PathPriorityProfile(PathPriorityReadBytes reader,void* user,PathPriorityExpectedBytes expected)
{
    if (!reader) return false;
    unsigned char bytes[24];
    for (size_t i=0;i<sizeof(windows)/sizeof(windows[0]);++i)
        if ((expected&&!expected(windows[i].rva,windows[i].count))
            || !reader(windows[i].rva,bytes,windows[i].count,user)
            || std::memcmp(bytes,expected?expected(windows[i].rva,windows[i].count):windows[i].expected,windows[i].count)!=0) return false;
    return true;
}
