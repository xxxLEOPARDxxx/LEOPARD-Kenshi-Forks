void PathPriorityEnter(PathPriorityFrame* f, PathPriorityContext*& slot, void* request,
    void* queue, const void* ret, int tier, bool repath, bool high, bool admitted)
{
    f->previous=slot;
    f->current.request=request; f->current.queue=queue; f->current.enqueueReturn=ret;
    f->current.tier=tier; f->current.nativePriority=high?20:10;
    f->current.repath=repath; f->current.admitted=admitted; f->current.consumed=false;
    slot=&f->current;
}
void PathPriorityLeave(const PathPriorityFrame* f, PathPriorityContext*& slot) { slot=f->previous; }
bool PathPriorityApply(PathPriorityContext* c, void* queue, void** item,
    const void* ret, PathPriorityDecision* decision)
{
    if (!decision) return false;
    decision->repath=false;
    if (!c || !c->admitted || c->consumed || c->tier<=0 || !c->request || !c->queue
        || !c->enqueueReturn || queue!=c->queue || ret!=c->enqueueReturn || !item) return false;
    if (*item!=c->request) return false;
    if (c->nativePriority!=10 && c->nativePriority!=20) return false;
    unsigned char* request=static_cast<unsigned char*>(c->request);
    int kind=0, priority=0;
    std::memcpy(&kind,request+0x28,sizeof(kind));
    std::memcpy(&priority,request+0x2C,sizeof(priority));
    if (kind!=0 || priority!=c->nativePriority || c->tier<=priority) return false;
    c->consumed=true;
    std::memcpy(request+0x2C,&c->tier,sizeof(c->tier));
    decision->repath=c->repath;
    return true;
}
bool PathPriorityCapability(bool wanted,bool profile,bool requestHook,bool submitHook,bool enqueueHook,bool originals)
{ return wanted && profile && requestHook && submitHook && enqueueHook && originals; }

